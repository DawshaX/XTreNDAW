    added = {"hadiths": 0, "adhkar": 0, "duas": 0, "info": 0}
    plans = (("hadiths", HADITHS), ("adhkar", ADHKAR),
             ("duas", DUAS), ("info", INFO))
    for key, items in plans:
        existing = {x["text"][:30] for x in stock.get(key, [])}
        for text, src in items:
            if text[:30] in existing:
                continue
            stock.setdefault(key, []).append({"text": text, "src": src})
            existing.add(text[:30])
            added[key] += 1
    STOCK.write_text(json.dumps(stock, ensure_ascii=False, indent=1),
                     encoding="utf-8")
    print("مضاف:", added)
    print("الإجمالي:", {k: len(v) for k, v in stock.items()})


